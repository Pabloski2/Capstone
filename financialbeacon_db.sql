-- =====================================================================
-- Financial Beacon - Faro Financiero
-- Esquema de base de datos (PostgreSQL; también corre en H2 modo PostgreSQL)
-- Coincide con las entidades JPA: User, Gasto, Deuda, IngresoMensual,
-- RecuperacionPassword y SoporteTicket
-- Nombres de columna según la estrategia por defecto de Spring Boot
-- (camelCase -> snake_case: montoTotal -> monto_total)
-- =====================================================================

DROP TABLE IF EXISTS soporte_tickets;
DROP TABLE IF EXISTS recuperaciones_password;
DROP TABLE IF EXISTS gastos;
DROP TABLE IF EXISTS deudas;
DROP TABLE IF EXISTS ingresos_mensuales;
DROP TABLE IF EXISTS users;

-- ---------------------------------------------------------------------
-- users
-- ---------------------------------------------------------------------
CREATE TABLE users (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email               VARCHAR(255) NOT NULL,
    password            VARCHAR(255) NOT NULL,
    nombre              VARCHAR(255) NOT NULL,
    -- datos personales (se completan en el primer inicio de sesión)
    apellido            VARCHAR(255),
    fecha_nacimiento    DATE,
    telefono            VARCHAR(255),
    ciudad              VARCHAR(255),
    ocupacion           VARCHAR(255),
    tipo_ingreso        VARCHAR(20) CHECK (tipo_ingreso IN ('FIJO', 'VARIABLE', 'MIXTO')),
    foto_perfil         VARCHAR(300000),   -- data URL de la foto, reducida en el celular
    cambio_password_en  BIGINT,            -- segundos desde 1970; invalida sesiones anteriores
    CONSTRAINT uk_users_email UNIQUE (email)
);

-- ---------------------------------------------------------------------
-- ingresos_mensuales (un ingreso por usuario, mes y año)
-- ---------------------------------------------------------------------
CREATE TABLE ingresos_mensuales (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    monto    NUMERIC(14,2) NOT NULL CHECK (monto >= 0),
    mes      INTEGER       NOT NULL CHECK (mes BETWEEN 1 AND 12),
    anio     INTEGER       NOT NULL CHECK (anio >= 2000),
    user_id  BIGINT        NOT NULL,
    CONSTRAINT fk_ingresos_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT uk_ingreso_user_mes_anio UNIQUE (user_id, mes, anio)
);

-- ---------------------------------------------------------------------
-- gastos (categoria = enum Categoria: FIJO | VARIABLE | HORMIGA)
-- ---------------------------------------------------------------------
CREATE TABLE gastos (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion  VARCHAR(255)  NOT NULL,
    monto        NUMERIC(14,2) NOT NULL CHECK (monto > 0),
    categoria    VARCHAR(20)   NOT NULL CHECK (categoria IN ('FIJO', 'VARIABLE', 'HORMIGA')),
    fecha        DATE          NOT NULL,
    user_id      BIGINT        NOT NULL,
    CONSTRAINT fk_gastos_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- Soporta findByUserIdAndFechaBetween[AndCategoria]
CREATE INDEX idx_gastos_user_fecha     ON gastos (user_id, fecha);
CREATE INDEX idx_gastos_user_fecha_cat ON gastos (user_id, fecha, categoria);

-- ---------------------------------------------------------------------
-- deudas
-- ---------------------------------------------------------------------
CREATE TABLE deudas (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(255)  NOT NULL,
    monto_total   NUMERIC(14,2) NOT NULL CHECK (monto_total >= 0),
    tasa_interes  NUMERIC(7,2)  NOT NULL CHECK (tasa_interes >= 0),
    cuota_minima  NUMERIC(14,2) NOT NULL CHECK (cuota_minima >= 0),
    user_id       BIGINT        NOT NULL,
    CONSTRAINT fk_deudas_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- Soporta findByUserId
CREATE INDEX idx_deudas_user ON deudas (user_id);

-- ---------------------------------------------------------------------
-- recuperaciones_password (código de 6 dígitos enviado por correo, guardado con hash)
-- ---------------------------------------------------------------------
CREATE TABLE recuperaciones_password (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email        VARCHAR(255) NOT NULL,
    codigo_hash  VARCHAR(255) NOT NULL,
    expira_en    TIMESTAMP WITH TIME ZONE NOT NULL,
    intentos     INTEGER NOT NULL DEFAULT 0,
    creado_en    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_recuperaciones_email ON recuperaciones_password (email);

-- ---------------------------------------------------------------------
-- soporte_tickets
-- ---------------------------------------------------------------------
CREATE TABLE soporte_tickets (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asunto     VARCHAR(150)  NOT NULL,
    categoria  VARCHAR(20)   NOT NULL CHECK (categoria IN ('CUENTA', 'ERROR', 'SUGERENCIA', 'OTRO')),
    mensaje    VARCHAR(2000) NOT NULL,
    estado     VARCHAR(20)   NOT NULL,
    creado_en  TIMESTAMP WITH TIME ZONE NOT NULL,
    user_id    BIGINT        NOT NULL,
    CONSTRAINT fk_tickets_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE INDEX idx_tickets_user ON soporte_tickets (user_id, creado_en);

